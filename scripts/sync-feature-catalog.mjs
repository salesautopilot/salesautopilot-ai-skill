#!/usr/bin/env node
// Regenerates the feature-catalog skill's reference file from the "Funkciók" Webflow CMS
// collection that powers https://www.salesautopilot.hu/arak and /funkciok-osszehasonlitasa.
//
// Usage:
//   WEBFLOW_API_TOKEN=... node scripts/sync-feature-catalog.mjs          # fetch live items
//   node scripts/sync-feature-catalog.mjs --from-file items.json        # render a saved {items:[...]} dump
//
// The token only needs the `cms:read` scope.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const COLLECTION_ID = '649ae01e3bd1486afa963954'; // Funkciók
const SITE_URL = 'https://www.salesautopilot.hu';
const OUTPUT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../salesautopilot/skills/salesautopilot-feature-catalog/references/feature-catalog.md',
);

// Column order matches the comparison table on the website.
const PACKAGES = [
  { code: 'ING', name: 'Ingyenes', check: 'kezdo-csomag-resze-pipa', note: 'kezdo-csomag-resze-leirassal' },
  { code: 'EM', name: 'Email Marketing', check: 'email-marketing-csomag-resze-pipa', note: 'email-marketing-csomag-resze-leirassal' },
  { code: 'AUT', name: 'Automatizálás', check: 'automatizalas-csomag-resze-pipa', note: 'automatizalas-csomag-resze-leirassal' },
  { code: 'ECO', name: 'Ecommerce', check: 'ecommerce-csomag-resze-pipa', note: 'ecommerce-csomag-resze-leirassal' },
  { code: 'FULL', name: 'Mindent Bele', check: 'full', note: 'full-szoveges-leiras' },
];

// Rows below this `sorrend` are the category-level summary rows of the /arak page;
// the detailed comparison list starts at the first category header (99.9).
const DETAILED_LIST_START = 99;

async function fetchLiveItems(token) {
  const items = [];
  for (let offset = 0; ; offset += 100) {
    const res = await fetch(
      `https://api.webflow.com/v2/collections/${COLLECTION_ID}/items/live?limit=100&offset=${offset}`,
      { headers: { Authorization: `Bearer ${token}`, accept: 'application/json' } },
    );
    if (!res.ok) throw new Error(`Webflow API ${res.status}: ${await res.text()}`);
    const page = await res.json();
    items.push(...page.items);
    if (items.length >= page.pagination.total || page.items.length === 0) return items;
  }
}

const clean = (s) => (s ?? '').replace(/\s+/g, ' ').trim();

// "ING, AUT, ECO, FULL" plus any per-package note (trial period, API quota, extra fee...).
// A note can exist without the checkmark (e.g. "60 napos ingyenes kipróbálás"), so both are shown.
function availability(f) {
  const included = PACKAGES.filter((p) => f[p.check]).map((p) => p.code);
  const notes = new Map();
  for (const p of PACKAGES) {
    const note = clean(f[p.note]);
    if (note) notes.set(note, [...(notes.get(note) ?? []), p.code]);
  }
  const parts = [included.length ? included.join(', ') : 'egyik csomagban sem alapértelmezett'];
  for (const [note, codes] of notes) {
    parts.push(codes.length === PACKAGES.length ? note : `${codes.join(', ')}: ${note}`);
  }
  return parts.join(' — ');
}

function render(rawItems) {
  // Drafts and archived items are not visible on the website, so they must not reach the AI either.
  // `hatterinformaciok` is internal-only and deliberately never rendered (the repo is public).
  const rows = rawItems
    .filter((x) => !x.isDraft && !x.isArchived)
    .map((x) => x.fieldData)
    .sort((a, b) => a.sorrend - b.sorrend);

  const overview = rows.filter((f) => f.sorrend < DETAILED_LIST_START);
  const detailed = rows.filter((f) => f.sorrend >= DETAILED_LIST_START);

  const out = [
    '# SalesAutopilot funkciókatalógus',
    '',
    `<!-- GENERATED by scripts/sync-feature-catalog.mjs from the Webflow "Funkciók" CMS collection. Do not edit by hand. -->`,
    '',
    `Forrás: ${SITE_URL}/funkciok-osszehasonlitasa (részletes lista) és ${SITE_URL}/arak (áttekintés).`,
    '',
    '**Csomagkódok:** ' + PACKAGES.map((p) => `\`${p.code}\` = ${p.name}`).join(', ') + '.',
    'A „Csomag” sor azt mutatja, melyik csomagban érhető el a funkció; a kötőjel utáni szöveg csomagonkénti megjegyzés (pl. próbaidő, API-keret, külön díj).',
    '',
    '## Áttekintés — funkciócsoportok',
    '',
    '| Funkciócsoport | Csomag |',
    '|---|---|',
    ...overview.map((f) => `| ${clean(f.name)} | ${availability(f).replace(/\|/g, '\\|')} |`),
  ];

  for (const f of detailed) {
    if (f['kategoria-cimsor']) {
      out.push('', `## ${clean(f.name)}`, '');
      continue;
    }
    out.push(`- **${clean(f.name)}**`);
    out.push(`  - Csomag: ${availability(f)}`);
    if (clean(f.tooltip)) out.push(`  - ${clean(f.tooltip)}`);
    if (f['szerepeljen-e-a-marketing-szotarban']) out.push(`  - Bővebben: ${SITE_URL}/funkciok/${f.slug}`);
  }

  return out.join('\n') + '\n';
}

async function main() {
  const fromFileIdx = process.argv.indexOf('--from-file');
  let items;
  if (fromFileIdx !== -1) {
    items = JSON.parse(await readFile(process.argv[fromFileIdx + 1], 'utf8')).items;
  } else {
    const token = process.env.WEBFLOW_API_TOKEN;
    if (!token) throw new Error('WEBFLOW_API_TOKEN is not set (or pass --from-file <dump.json>).');
    items = await fetchLiveItems(token);
  }
  await writeFile(OUTPUT, render(items));
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} from ${items.length} CMS items.`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
